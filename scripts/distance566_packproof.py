"""Export compact, equal-weight partial packing certificates for the final code.

The input remains untrusted. Lean proves row-combination membership, capacities,
and the strict integer thresholds. Run this generator in a bounded allocation.
"""

import argparse
import gzip
import json
import random
from collections import Counter
from pathlib import Path

from distance566 import coordinates, pack, verify_family
from emit_removal566 import HASHES, REVISION, read_code


def prune(family, bound, rng):
    """Delete representatives only while the required strict threshold holds."""
    best = family
    for _ in range(12):
        candidate = list(family)
        rng.shuffle(candidate)
        loads = Counter(q for entry in candidate for q in entry["support"])
        for entry in list(candidate):
            new_loads = loads.copy()
            new_loads.subtract(entry["support"])
            if (bound - 1) * max(new_loads.values(), default=0) < len(candidate) - 1:
                candidate.remove(entry)
                loads = new_loads
        if len(candidate) < len(best):
            best = candidate
    return best


def export(code, record, output):
    data = coordinates(code)
    selected = {}
    for entry in record["families"]:
        if entry["n"] == 566:
            key = (entry["side"], entry["coordinate"])
            if key in selected:
                raise ValueError("Duplicate family")
            selected[key] = entry
    if set(selected) != {(s, i) for s in ("X", "Z") for i in range(18)}:
        raise ValueError("Incomplete logical-coordinate basis")
    bound = min(entry["arithmetic"]["bound"] for entry in selected.values())
    if bound < 2:
        raise ValueError("No useful partial packing bound")
    rng = random.Random(56622)
    compact = []
    for s in ("X", "Z"):
        rows = [pack(r) for r in code["checks"][s]]
        for i in range(18):
            entry = selected[s, i]
            if any(r["weight"] != 1 for r in entry["family"]):
                raise ValueError("This compact emitter expects equal weights")
            family = prune(entry["family"], bound, rng)
            arithmetic = verify_family(rows, pack(data[s][i]), 566, family)
            if not (bound - 1) * arithmetic["cap"] < arithmetic["totalWeight"]:
                raise ValueError("Failed strict integer threshold")
            compact.append(
                {"n": 566, "side": s, "coordinate": i, "family": family, "arithmetic": arithmetic}
            )
    output.mkdir(parents=True, exist_ok=True)
    text = (
        "import QldpcVerification.Distance566Certificates\n"
        "import QldpcVerification.Input.Removal566Data\n\n"
        "/-! Generated by scripts/distance566_packproof.py.\n"
        f"Challenge revision: {REVISION}\n566 SHA256: {HASHES[566]}\n"
        "Partial equal-weight packing certificates, with actual stabilizer row witnesses. -/\n"
        "namespace QldpcVerification.Distance566.PackingData\n"
        "open Input.Sparse Distance566Certificates\n"
        "set_option maxRecDepth 100000\nset_option maxHeartbeats 0\n\n"
        f"def bound : ℕ := {bound}\n\n"
    )
    for s in ("X", "Z"):
        name = s.lower()
        entries = [e for e in compact if e["side"] == s]
        text += f"def {name}Reps : List (List (ℕ × List (Fin 274))) := [\n"
        lines = []
        for entry in entries:
            reps = []
            for r in entry["family"]:
                indices = ", ".join(f"⟨{i}, by decide⟩" for i in r["rows"])
                reps.append(f"({pack(r['support'])}, [{indices}])")
            lines.append("  [" + ",\n   ".join(reps) + "]")
        text += ",\n".join(lines) + "]\n\n"
        text += (
            f"def {name}Caps : List ℕ := ["
            + ", ".join(str(e["arithmetic"]["cap"]) for e in entries)
            + "]\n\n"
        )
        text += (
            f"def {name}Family (a : Fin 18) : List (ℕ × ℕ) :=\n"
            f"  ({name}Reps.get a).map fun r => (r.1, 1)\n\n"
        )
    text += "end QldpcVerification.Distance566.PackingData\n"
    (output / "Distance566PackingData.lean").write_text(text)
    for block in range(3):
        text = (
            "import QldpcVerification.Input.Distance566PackingData\n"
            "import QldpcVerification.Input.Distance566Data\n\n"
            "namespace QldpcVerification.Distance566.PackingChecks\n"
            "open Input.Sparse Distance566Certificates PackingData\n"
            "set_option maxRecDepth 100000\nset_option maxHeartbeats 0\n\n"
        )
        for i in range(6 * block, 6 * block + 6):
            for name, rows in (("x", "hx"), ("z", "hz")):
                a = f"⟨{i}, by decide⟩"
                text += (
                    f"theorem {name}Class{i} : classCheck Removal566.Stage12.{rows} "
                    f"(Data.{name}Masks.get {a}) ({name}Reps.get {a}) = true := by decide +kernel\n\n"
                    f"theorem {name}Cap{i} : capCheck 566 ({name}Family {a}) "
                    f"({name}Caps.get {a}) = true := by decide +kernel\n\n"
                    f"theorem {name}Threshold{i} : (bound - 1) * ({name}Caps.get {a}) < "
                    f"(({name}Family {a}).map Prod.snd).sum := by decide +kernel\n\n"
                )
        text += "end QldpcVerification.Distance566.PackingChecks\n"
        (output / f"Distance566PackingChecks{block}.lean").write_text(text)
    text = "".join(
        f"import QldpcVerification.Input.Distance566PackingChecks{i}\n" for i in range(3)
    )
    text += (
        "\nnamespace QldpcVerification.Distance566.PackingChecks\n"
        "open Input.Sparse Distance566Certificates PackingData\n"
        "set_option maxRecDepth 100000\nset_option maxHeartbeats 0\n\n"
    )
    for name, rows in (("x", "hx"), ("z", "hz")):
        for suffix, expression in (
            (
                "Class",
                f"classCheck Removal566.Stage12.{rows} (Data.{name}Masks.get a) ({name}Reps.get a) = true",
            ),
            ("Cap", f"capCheck 566 ({name}Family a) ({name}Caps.get a) = true"),
            (
                "Threshold",
                f"(bound - 1) * ({name}Caps.get a) < (({name}Family a).map Prod.snd).sum",
            ),
        ):
            text += f"theorem {name}{suffix} : ∀ a : Fin 18, {expression} := by\n  intro a\n  fin_cases a\n"
            text += "".join(f"  · exact {name}{suffix}{i}\n" for i in range(18)) + "\n"
    text += "end QldpcVerification.Distance566.PackingChecks\n"
    (output / "Distance566PackingChecks.lean").write_text(text)
    return {"revision": REVISION, "bound": bound, "families": compact}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--upstream", type=Path, required=True)
    parser.add_argument("--packing", type=Path, required=True)
    parser.add_argument("--out", type=Path, required=True)
    parser.add_argument("--lean-root", type=Path, required=True)
    args = parser.parse_args()
    code = read_code(args.upstream / "codes/566-18-20.json", 566)
    opener = gzip.open if args.packing.suffix == ".gz" else open
    with opener(args.packing, "rt") as stream:
        record = json.load(stream)
    compact = export(code, record, args.lean_root / "Input")
    args.out.write_text(json.dumps(compact, indent=2) + "\n")
    print(
        json.dumps(
            {
                "bound": compact["bound"],
                "family_sizes": [len(e["family"]) for e in compact["families"]],
            }
        )
    )


if __name__ == "__main__":
    main()
