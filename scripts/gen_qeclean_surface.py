"""Generate matrix input and QECLean face labels for the surface-code proof.

This script uses only the standard library. Lean checks every generated label,
the complete row supports, and surjectivity of both row maps.
"""

import argparse
import hashlib
import json
from pathlib import Path


def face_label(row, side, size=15):
    """Rotate board index size*r+c to QECLean vertex (size-1-r,c)."""
    n = size * size
    if side not in {"X", "Z"}:
        raise ValueError(f"Unknown check type: {side}")
    if len(row) not in {2, 4} or len(set(row)) != len(row):
        raise ValueError(f"Expected two or four distinct qubits: {row}")
    if any(type(q) is not int or not 0 <= q < n for q in row):
        raise ValueError(f"Qubit outside Fin {n}: {row}")
    vertices = {(size - 1 - q // size, q % size) for q in row}
    xs = sorted({v[0] for v in vertices})
    ys = sorted({v[1] for v in vertices})
    if len(vertices) == 4 and len(xs) == len(ys) == 2:
        x, y = xs[0], ys[0]
        assert xs == [x, x + 1] and ys == [y, y + 1]
        assert (x + y) % 2 == (side == "X")
        return f".interior ⟨(⟨{x}, by decide⟩, ⟨{y}, by decide⟩), by decide⟩"
    assert len(vertices) == 2
    if side == "X" and ys == [0] and xs[0] % 2 == 0:
        label, k = "topBdy", xs[0] // 2
    elif side == "X" and ys == [size - 1] and xs[0] % 2 == 1:
        label, k = "bottomBdy", (xs[0] - 1) // 2
    elif side == "Z" and xs == [0] and ys[0] % 2 == 1:
        label, k = "leftBdy", (ys[0] - 1) // 2
    elif side == "Z" and xs == [size - 1] and ys[0] % 2 == 0:
        label, k = "rightBdy", ys[0] // 2
    else:
        raise ValueError(f"No QECLean face for {side} support {row}")
    assert (len(xs) == 1 and ys[1] == ys[0] + 1) or (len(ys) == 1 and xs[1] == xs[0] + 1)
    return f".{label} ⟨{k}, by decide⟩"


def generate(source, size=15):
    raw = source.read_bytes()
    code = json.loads(raw)
    n = size * size
    count = (n - 1) // 2
    if size < 3 or size % 2 != 1 or code["n"] != n or code["code_type"] != "CSS":
        raise ValueError(f"This adapter accepts a CSS code on {n} qubits.")
    parts = [
        "import QEC.Stabilizer.Codes.RotatedSurface.CellComplex\n",
        "/-! Generated by scripts/gen_qeclean_surface.py. Lean checks these labels.\n"
        f"Input SHA256: {hashlib.sha256(raw).hexdigest()} -/\n",
        f"namespace QldpcVerification.Surface{n}\n",
        "open Quantum.Stabilizer.Lattice.RotatedSurface\n",
    ]
    for side in ("X", "Z"):
        labels = [face_label(row, side, size) for row in code["checks"][side]]
        assert len(labels) == count and len(set(labels)) == count
        parts.append(
            f"def {side.lower()}Faces : List ({side}FaceIdx {size}) := [\n  "
            + ",\n  ".join(labels)
            + "]\n"
        )
    parts.append(f"end QldpcVerification.Surface{n}\n")
    return "\n".join(parts)


def generate_supports(source, size=15):
    """Emit the submitted rows directly, without the archived rank certificates."""
    raw = source.read_bytes()
    code = json.loads(raw)
    n = size * size
    count = (n - 1) // 2
    if size < 3 or size % 2 != 1 or code["n"] != n or code["code_type"] != "CSS":
        raise ValueError(f"This adapter accepts a CSS code on {n} qubits.")
    parts = [
        "import Mathlib.Data.Finset.Insert\n",
        f"/-! Generated by scripts/gen_qeclean_surface.py from codes/{source.name}.\n"
        f"Input SHA256: {hashlib.sha256(raw).hexdigest()} -/\n",
        f"namespace QldpcVerification.Input.Surface{n}\n",
    ]
    for side in ("X", "Z"):
        rows = code["checks"][side]
        if len(rows) != count:
            raise ValueError(f"Expected {count} {side} checks.")
        sets = []
        for row in rows:
            face_label(row, side, size)  # Reject malformed supports before emitting Fin indices.
            sets.append("{" + ", ".join(f"⟨{q}, by decide⟩" for q in row) + "}")
        parts.append(
            f"def h{side.lower()}Support : List (Finset (Fin {n})) := [\n  "
            + ",\n  ".join(sets)
            + "]\n"
        )
    parts.append(f"end QldpcVerification.Input.Surface{n}\n")
    return "\n".join(parts)


def generate_lookup(source, size):
    """Emit inverse row maps so Lean need not search for each canonical face."""
    raw = source.read_bytes()
    code = json.loads(raw)
    generate(source, size)  # Validate the complete family before constructing the inverse.
    parts = [
        "import Mathlib.Data.List.Basic\n",
        "/-! Generated inverse row maps. Lean checks their right-inverse equations.\n"
        f"Input SHA256: {hashlib.sha256(raw).hexdigest()} -/\n",
        f"namespace QldpcVerification.Surface{size * size}\n",
    ]
    for side in ("X", "Z"):
        interior = [0] * ((size - 1) ** 2)
        first, second = [0] * ((size - 1) // 2), [0] * ((size - 1) // 2)
        for i, row in enumerate(code["checks"][side]):
            vertices = [(size - 1 - q // size, q % size) for q in row]
            x, y = min(v[0] for v in vertices), min(v[1] for v in vertices)
            if len(row) == 4:
                interior[y * (size - 1) + x] = i
            elif side == "X":
                if y == 0:
                    first[x // 2] = i
                else:
                    second[(x - 1) // 2] = i
            elif x == 0:
                first[(y - 1) // 2] = i
            else:
                second[y // 2] = i
        for name, values in [("Interior", interior), ("First", first), ("Second", second)]:
            parts.append(
                f"def {side.lower()}{name}Rows : List Nat := ["
                + ", ".join(map(str, values))
                + "]\n"
            )
    parts.append(f"end QldpcVerification.Surface{size * size}\n")
    return "\n".join(parts)


def generate_match(size):
    """Recognize the submitted rows and instantiate the shared family theorem."""
    template = """import QldpcVerification.RotatedSurface
import QldpcVerification.Input.Surface@N@Labels
import QldpcVerification.Input.Surface@N@Support
import QldpcVerification.Input.Surface@N@Lookup

/-! Generated recognition certificate. All finite facts are checked by the kernel. -/
namespace QldpcVerification.Surface@N@

open Matrix Quantum.Stabilizer.Lattice.RotatedSurface

set_option maxRecDepth 100000
set_option maxHeartbeats 0

def qubitEquiv : VtxIdx @L@ ≃ Fin @N@ :=
  (Equiv.prodCongr
    (show Fin @L@ ≃ Fin @L@ from
      { toFun := Fin.rev, invFun := Fin.rev,
        left_inv := Fin.rev_rev, right_inv := Fin.rev_rev })
    (Equiv.refl (Fin @L@))).trans finProdFinEquiv

def xFace (i : Fin @M@) : XFaceIdx @L@ := xFaces.get i
def zFace (i : Fin @M@) : ZFaceIdx @L@ := zFaces.get i

def xPreimage : XFaceIdx @L@ → Fin @M@
  | .interior c => ⟨xInteriorRows.getD (c.val.2.val * (@L@ - 1) + c.val.1.val) 0 % @M@,
      Nat.mod_lt _ (by decide)⟩
  | .topBdy k => ⟨xFirstRows.getD k.val 0 % @M@, Nat.mod_lt _ (by decide)⟩
  | .bottomBdy k => ⟨xSecondRows.getD k.val 0 % @M@, Nat.mod_lt _ (by decide)⟩

def zPreimage : ZFaceIdx @L@ → Fin @M@
  | .interior c => ⟨zInteriorRows.getD (c.val.2.val * (@L@ - 1) + c.val.1.val) 0 % @M@,
      Nat.mod_lt _ (by decide)⟩
  | .leftBdy k => ⟨zFirstRows.getD k.val 0 % @M@, Nat.mod_lt _ (by decide)⟩
  | .rightBdy k => ⟨zSecondRows.getD k.val 0 % @M@, Nat.mod_lt _ (by decide)⟩

theorem x_right_inverse : ∀ f, xFace (xPreimage f) = f := by decide +kernel
theorem z_right_inverse : ∀ f, zFace (zPreimage f) = f := by decide +kernel

theorem x_surjective : Function.Surjective xFace := fun f => ⟨_, x_right_inverse f⟩

theorem z_surjective : Function.Surjective zFace :=
  fun f => ⟨_, z_right_inverse f⟩

theorem x_support_match : ∀ i : Fin @M@,
    Input.Surface@N@.hxSupport.get i = (xSupport (xFace i)).image qubitEquiv := by
  decide +kernel

theorem z_support_match : ∀ i : Fin @M@,
    Input.Surface@N@.hzSupport.get i = (zSupport (zFace i)).image qubitEquiv := by
  decide +kernel

def certificate : RotatedSurfaceMatch @L@ @N@ @M@ @M@ where
  HX := fun i q => if q ∈ Input.Surface@N@.hxSupport.get i then 1 else 0
  HZ := fun i q => if q ∈ Input.Surface@N@.hzSupport.get i then 1 else 0
  qubits := qubitEquiv
  xFace := xFace
  zFace := zFace
  x_surjective := x_surjective
  z_surjective := z_surjective
  x_rows := by
    intro i
    funext v
    change (if qubitEquiv v ∈ Input.Surface@N@.hxSupport.get i then (1 : ZMod 2) else 0) =
      if v ∈ xSupport (xFace i) then 1 else 0
    rw [x_support_match i]
    simp
  z_rows := by
    intro i
    funext v
    change (if qubitEquiv v ∈ Input.Surface@N@.hzSupport.get i then (1 : ZMod 2) else 0) =
      if v ∈ zSupport (zFace i) then 1 else 0
    rw [z_support_match i]
    simp

end QldpcVerification.Surface@N@
"""
    return (
        template.replace("@N@", str(size * size))
        .replace("@L@", str(size))
        .replace("@M@", str((size * size - 1) // 2))
    )


def generate_instance(size):
    template = """import QldpcVerification.Input.Surface@N@Match

namespace QldpcVerification.Surface@N@

local instance : Fact (Odd @L@) := ⟨by decide⟩
local instance : Fact (3 ≤ @L@) := ⟨by decide⟩

abbrev code := certificate.code

theorem parameters :
    (@N@ - Module.finrank (ZMod 2) code.xStab - Module.finrank (ZMod 2) code.zStab = 1) ∧
      code.DistX @L@ ∧ code.DistZ @L@ := certificate.parameters

end QldpcVerification.Surface@N@
"""
    return template.replace("@N@", str(size * size)).replace("@L@", str(size))


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("source", type=Path)
    parser.add_argument("output", type=Path)
    parser.add_argument("--size", type=int, default=15)
    parser.add_argument("--supports", type=Path, help="Also emit the submitted sparse matrices.")
    parser.add_argument("--match", type=Path, help="Emit a recognition certificate for the family.")
    parser.add_argument("--lookup", type=Path, help="Emit inverse row maps for recognition.")
    parser.add_argument("--instance", type=Path, help="Emit the instance theorem.")
    args = parser.parse_args()
    args.output.write_text(generate(args.source, args.size))
    if args.supports:
        args.supports.write_text(generate_supports(args.source, args.size))
    if args.match:
        args.match.write_text(generate_match(args.size))
    if args.lookup:
        args.lookup.write_text(generate_lookup(args.source, args.size))
    if args.instance:
        args.instance.write_text(generate_instance(args.size))


if __name__ == "__main__":
    main()
