"""Emit the submitted 562-qubit matrices and finite certificates for the lattice proof.

Lean checks the graph recognition, rank bounds, logical coordinates, and witnesses.
The lattice lower bound itself is a reusable mathematical proof, not a search result.
"""

import argparse
import hashlib
import json
from pathlib import Path

import common
import numpy as np
from common import gf2


def generate(source):
    raw = source.read_bytes()
    code = json.loads(raw)
    if code["n"] != 562 or code["code_type"] != "CSS":
        raise ValueError("This emitter accepts the 562-qubit CSS lattice instance.")
    n, g = 562, 281
    expected = {
        "X": (158, 165, 135, 280),
        "Z": (1, 146, 116, 123),
    }
    matrices = {}
    for side, (a, b, c, d) in expected.items():
        rows = code["checks"][side]
        if len(rows) != g:
            raise ValueError(f"Expected {g} {side} checks.")
        for i, row in enumerate(rows):
            want = {(i + a) % g, (i + b) % g, g + (i + c) % g, g + (i + d) % g}
            if len(row) != 4 or set(row) != want:
                raise ValueError(f"Unexpected {side} row {i}.")
        matrices[side] = common.matrix(rows, n)
    parts = [
        "import Mathlib.Data.Finset.Insert\nimport Mathlib.Data.Fintype.Fin\n",
        "/-! Generated by scripts/gen_bicycle_lattice.py from codes/562-2-23.json.\n"
        f"Input SHA256: {hashlib.sha256(raw).hexdigest()} -/\n",
        "namespace QldpcVerification.Bicycle562Data\n",
        "set_option maxRecDepth 100000\n",
        "def nq : Nat := 562\ndef target : Nat := 23\n",
    ]

    def emit(name, values, typ="Nat"):
        parts.append(f"def {name} : List ({typ}) := [\n  " + ",\n  ".join(map(str, values)) + "]\n")

    def supports(name, rows, size):
        emit(
            name,
            [
                "{" + ", ".join(f"⟨{int(q)}, by decide⟩" for q in np.flatnonzero(v)) + "}"
                for v in rows
            ],
            f"Finset (Fin {size})",
        )

    for side in ("x", "z"):
        h = matrices[side.upper()]
        if gf2.rank(h) != g - 1:
            raise ValueError("The submitted matrix does not have the expected rank.")
        supports(f"h{side}", h, n)
        w = np.zeros(n, dtype=np.int8)
        w[code["distance"][side.upper()]["witness"]] = 1
        if int(w.sum()) != 23 or (matrices[{"x": "Z", "z": "X"}[side]] @ w % 2).any():
            raise ValueError("The stored weight-23 witness fails its syndrome check.")
        if gf2.in_rowspace(w, h):
            raise ValueError("The stored witness is a stabilizer.")
        parts.append(f"def w{side} : Nat := {sum(1 << int(q) for q in np.flatnonzero(w))}\n")
    parts.append(
        "def blocks : List (Finset (Fin 562)) := [\n"
        "  Finset.univ.filter (fun q => q.val < 281),\n"
        "  Finset.univ.filter (fun q => 281 ≤ q.val)]\n"
    )
    emit("blockMasks", [(1 << g) - 1, ((1 << g) - 1) << g])
    parts.append("end QldpcVerification.Bicycle562Data\n")
    return "\n".join(parts)


def generate_checks():
    parts = [
        "import QldpcVerification.Input.SparseCertificates",
        "import QldpcVerification.Input.Bicycle562Data",
        "",
        "namespace QldpcVerification.Bicycle562Checks",
        "open Input.Sparse Bicycle562Data",
        "set_option maxRecDepth 100000",
        "set_option maxHeartbeats 0",
        "",
    ]

    def check(name, proposition):
        parts.append(f"theorem {name} : {proposition} := by decide +kernel\n")

    for side, opposite in [("x", "z"), ("z", "x")]:
        check(
            f"{side}BlocksKernel", f"∀ i : Fin 2, kernelCheck h{opposite} (blockMasks.get i) = true"
        )
        check(f"w{side}Kernel", f"kernelCheck h{opposite} w{side} = true")
        check(f"w{side}Weight", f"(∑ q : Fin nq, if bit w{side} q then 1 else 0) = 23")
        check(f"w{side}Pair", f"∃ j : Fin 2, parity (blocks.get j) w{side} = true")
    parts.append("end QldpcVerification.Bicycle562Checks\n")
    return "\n".join(parts)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--source", type=Path, default=Path(common.code_file("562-2-23")))
    parser.add_argument(
        "--output", type=Path, default=Path("lean/QldpcVerification/Input/Bicycle562Data.lean")
    )
    parser.add_argument(
        "--checks", type=Path, default=Path("lean/QldpcVerification/Input/Bicycle562Checks.lean")
    )
    args = parser.parse_args()
    args.output.write_text(generate(args.source))
    args.checks.write_text(generate_checks())


if __name__ == "__main__":
    main()
