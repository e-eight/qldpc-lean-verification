"""Generate a Lean instance file for a k = 1 laid-out code with a line-packing
certificate (rotated surface codes), for the Lean pilot in ../lean/QldpcCert.

All vectors are emitted as natural-number bitmasks (bit q = qubit q). The
certificates the Lean proof checks are:
  * rank pivot certificates for H_X and H_Z: a transform T and pivot columns p
    with (T H)[i][p j] = [i = j]. Only lower bounds on the ranks are needed;
  * the stored X and Z witnesses (the upper bounds);
  * the line families: Z-type lines pairing to 1 with the X witness, which bound
    d_X, and X-type lines pairing to 1 with the Z witness, which bound d_Z.
Nothing is trusted from this script: Lean re-checks every fact it emits.

Usage: python scripts/gen_lean_instance.py <slug> <Module.Name> <out.lean>
"""
import os
import sys

import numpy as np

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import common  # noqa: E402
from common import gf2  # noqa: E402
from line_check import lines  # noqa: E402


def mask(support):
    return sum(1 << int(q) for q in support)


def rank_certificate(H):
    """Rows T (as masks over H's rows) and pivots p with (T H)[i][p_j] = [i = j]."""
    m, n = H.shape
    A = np.hstack([H, np.eye(m, dtype=np.int8)])
    R, piv = gf2.rref(A)
    piv = [c for c in piv if c < n]
    T = R[:len(piv), n:]
    TH = (T.astype(np.int64) @ H % 2).astype(np.int8)
    assert all(TH[i, piv[j]] == (i == j) for i in range(len(piv)) for j in range(len(piv)))
    return [mask(np.nonzero(t)[0]) for t in T], piv


def lean_array(name, values, typ="Nat"):
    body = ",\n  ".join(str(v) for v in values)
    return f"def {name} : List {typ} := [\n  {body}]\n"


def main(slug, module, out):
    d = common.load(common.code_file(slug))
    n = d["n"]
    HX = common.matrix(d["checks"]["X"], n)
    HZ = common.matrix(d["checks"]["Z"], n)
    assert n - gf2.rank(HX) - gf2.rank(HZ) == 1, "k = 1 only"
    wX, wZ = d["distance"]["X"]["witness"], d["distance"]["Z"]["witness"]
    vX, vZ = np.zeros(n, dtype=np.int8), np.zeros(n, dtype=np.int8)
    vX[wX] = 1
    vZ[wZ] = 1

    def family(H_opp, partner):
        """Largest set of disjoint layout lines that are logicals pairing to 1 with partner."""
        best = []
        for groups in lines(d["locality"]["coordinates"]).values():
            fam = []
            for g in groups:
                v = np.zeros(n, dtype=np.int8)
                v[g] = 1
                if not (H_opp @ v % 2).any() and int(v @ partner % 2) == 1:
                    fam.append(sorted(int(q) for q in g))
            if len(fam) > len(best):
                best = fam
        return best

    zlines = family(HX, vX)  # Z-type, bound d_X
    xlines = family(HZ, vZ)  # X-type, bound d_Z
    tX, pX = rank_certificate(HX)
    tZ, pZ = rank_certificate(HZ)
    mx, mz = HX.shape[0], HZ.shape[0]
    print(f"{slug}: n={n} mx={mx} mz={mz} rankX>={len(pX)} rankZ>={len(pZ)} "
          f"zlines={len(zlines)} xlines={len(xlines)} |wX|={len(wX)} |wZ|={len(wZ)}")

    parts = [
        f"/-! Generated by scripts/gen_lean_instance.py from codes/{slug}.json "
        f"(qldpc-challenge). Data only; every fact is re-checked in Lean. -/\n",
        "namespace " + module + "\n",
        f"def nq : Nat := {n}\ndef mX : Nat := {mx}\ndef mZ : Nat := {mz}\n",
        lean_array("hx", [mask(r) for r in d["checks"]["X"]]),
        lean_array("hz", [mask(r) for r in d["checks"]["Z"]]),
        f"def wX : Nat := {mask(wX)}\ndef wZ : Nat := {mask(wZ)}\n",
        f"def wXWeight : Nat := {len(wX)}\ndef wZWeight : Nat := {len(wZ)}\n",
        lean_array("zLines", [mask(g) for g in zlines]),
        lean_array("xLines", [mask(g) for g in xlines]),
        f"def rX : Nat := {len(pX)}\n", lean_array("tX", tX), lean_array("pX", pX),
        f"def rZ : Nat := {len(pZ)}\n", lean_array("tZ", tZ), lean_array("pZ", pZ),
        "end " + module + "\n",
    ]
    os.makedirs(os.path.dirname(os.path.abspath(out)), exist_ok=True)
    with open(out, "w") as fh:
        fh.write("\n".join(parts))
    print("wrote", out)


if __name__ == "__main__":
    main(*sys.argv[1:4])
