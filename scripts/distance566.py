"""Literal-matrix logical coordinates and bounded, untrusted packing experiments.

All numerical output is certificate input, not a distance proof. Run computation
inside a bounded allocation. No geometric symmetry is assumed by this script.
"""

import argparse
import hashlib
import json
import math
import random
import time
from pathlib import Path

from emit_removal566 import HASHES, REVISION, finset, read_code, support


def pack(indices):
    result = 0
    for q in indices:
        if type(q) is not int or q < 0 or (result >> q) & 1:
            raise ValueError("Support must contain distinct natural indices")
        result |= 1 << q
    return result


def dot(a, b):
    return (a & b).bit_count() % 2


def echelon(rows):
    basis = {}
    for v in rows:
        while v:
            p = v.bit_length() - 1
            if p not in basis:
                basis[p] = v
                break
            v ^= basis[p]
    return basis


def reduce_vector(v, basis):
    while v:
        p = v.bit_length() - 1
        if p not in basis:
            break
        v ^= basis[p]
    return v


def kernel(rows, n):
    basis = echelon(rows)
    for p in sorted(basis):
        for q in basis:
            if q > p and (basis[q] >> p) & 1:
                basis[q] ^= basis[p]
    return [
        (1 << q) ^ pack(p for p, v in basis.items() if (v >> q) & 1)
        for q in range(n)
        if q not in basis
    ]


def quotient_basis(checks, stabilizers, n, first):
    basis = echelon(stabilizers)
    result = []
    for v in [first, *kernel(checks, n)]:
        r = reduce_vector(v, basis)
        if r:
            basis[r.bit_length() - 1] = r
            result.append(v)
    return result


def combination(rows, coefficients):
    if coefficients < 0 or coefficients.bit_length() > len(rows):
        raise ValueError("Row-combination index is out of range")
    result = 0
    for i in support(coefficients):
        result ^= rows[i]
    return result


def dualize(xs, zs):
    """Gauss-Jordan on the pairing columns; preserve the chosen X witnesses."""
    zs = list(zs)
    k = len(xs)
    if len(zs) != k:
        raise ValueError("Unequal quotient dimensions")
    for i in range(k):
        pivot = next((j for j in range(i, k) if dot(xs[i], zs[j])), None)
        if pivot is None:
            raise ValueError("Degenerate logical pairing")
        zs[i], zs[pivot] = zs[pivot], zs[i]
        for j in range(k):
            if j != i and dot(xs[i], zs[j]):
                zs[j] ^= zs[i]
    return zs


def coordinates(code):
    n = code["n"]
    rows = {s: [pack(v) for v in code["checks"][s]] for s in ("X", "Z")}
    if any(dot(x, z) for x in rows["X"] for z in rows["Z"]):
        raise ValueError("Noncommuting input")
    ranks = {s: len(echelon(rs)) for s, rs in rows.items()}
    k = n - sum(ranks.values())
    if k != code["k"]:
        raise ValueError("Wrong logical dimension")
    stored = {s: pack(code["distance"][s]["witness"]) for s in ("X", "Z")}
    for s, opposite in (("X", "Z"), ("Z", "X")):
        if stored[s].bit_length() > n or any(dot(stored[s], r) for r in rows[opposite]):
            raise ValueError("Invalid stored witness syndrome")
        if not reduce_vector(stored[s], echelon(rows[s])):
            raise ValueError("Trivial stored witness")
        if stored[s].bit_count() != code["distance"][s]["value"]:
            raise ValueError("Wrong stored witness weight")
    xs = quotient_basis(rows["Z"], rows["X"], n, stored["X"])
    zs = dualize(xs, quotient_basis(rows["X"], rows["Z"], n, stored["Z"]))
    if len(xs) != k:
        raise ValueError("Incomplete logical basis")
    for opposite, vs in (("Z", xs), ("X", zs)):
        if any(dot(v, r) for v in vs for r in rows[opposite]):
            raise ValueError("Logical basis has nonzero syndrome")
    if any(dot(x, z) != (i == j) for i, x in enumerate(xs) for j, z in enumerate(zs)):
        raise ValueError("Logical bases are not paired")
    return {
        "n": n,
        "k": k,
        "ranks": ranks,
        "X": [support(v) for v in xs],
        "Z": [support(v) for v in zs],
        "stored_witnesses": {s: support(v) for s, v in stored.items()},
        "scope": "Numerical coordinates and upper witnesses; no lower distance bound",
    }


def emit_coordinates(record, output):
    """Emit only data; all semantic statements are proved in separate Lean modules."""
    header = (
        "import QldpcVerification.Input.SparseCertificates\n\n"
        "/-! Generated by scripts/distance566.py coordinates.\n"
        f"Challenge revision: {REVISION}\n566 SHA256: {HASHES[566]}\n"
        "Literal-matrix logical coordinates; no distance lower bound. -/\n"
        "namespace QldpcVerification.Distance566.Data\n"
        "open Input Input.Sparse\n"
        "set_option maxRecDepth 100000\n"
        "set_option maxHeartbeats 0\n\n"
    )
    for side in ("X", "Z"):
        name = side.lower()
        header += f"def {name}Masks : List ℕ := [\n  "
        header += ",\n  ".join(str(pack(v)) for v in record[side]) + "]\n\n"
        header += f"def {name}Supports : List (Finset (Fin 566)) := [\n  "
        header += ",\n  ".join(finset(v) for v in record[side]) + "]\n\n"
    header += "end QldpcVerification.Distance566.Data\n"
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text(header)
    # Separate evaluation blocks keep kernel-checking memory bounded.
    for block in range(3):
        text = (
            "import QldpcVerification.Input.Distance566Data\n"
            "import QldpcVerification.Input.Removal566Data\n\n"
            "namespace QldpcVerification.Distance566.Checks\n"
            "open Input.Sparse Data\n"
            "set_option maxRecDepth 100000\nset_option maxHeartbeats 0\n\n"
        )
        for i in range(6 * block, 6 * block + 6):
            for s, opposite in (("x", "hz"), ("z", "hx")):
                text += (
                    f"theorem {s}Kernel{i} : kernelCheck Removal566.Stage12.{opposite} "
                    f"({s}Masks.get ⟨{i}, by decide⟩) = true := by decide +kernel\n\n"
                )
            text += (
                f"theorem zVector{i} : vectorCheck (zMasks.get ⟨{i}, by decide⟩) "
                f"(zSupports.get ⟨{i}, by decide⟩) = true := by decide +kernel\n\n"
            )
        text += "end QldpcVerification.Distance566.Checks\n"
        (output.parent / f"Distance566Checks{block}.lean").write_text(text)
    text = "".join(
        f"import QldpcVerification.Input.Distance566Checks{block}\n" for block in range(3)
    )
    text += (
        "\nnamespace QldpcVerification.Distance566.Checks\n"
        "open Input.Sparse Data\n"
        "set_option maxRecDepth 100000\nset_option maxHeartbeats 0\n\n"
    )
    for name, expression in (
        ("xKernel", "kernelCheck Removal566.Stage12.hz (xMasks.get i) = true"),
        ("zKernel", "kernelCheck Removal566.Stage12.hx (zMasks.get i) = true"),
        ("zVector", "vectorCheck (zMasks.get i) (zSupports.get i) = true"),
    ):
        text += f"theorem {name} : ∀ i : Fin 18, {expression} := by\n"
        text += "  intro i\n  fin_cases i\n"
        text += "".join(f"  · exact {name}{i}\n" for i in range(18)) + "\n"
    text += (
        "theorem paired : pairingCheck zSupports xMasks = true := by decide +kernel\n\n"
        "theorem xWeight : (∑ q : Fin 566, if bit (xMasks.get ⟨0, by decide⟩) q "
        "then 1 else 0) = 20 := by decide +kernel\n\n"
        "end QldpcVerification.Distance566.Checks\n"
    )
    (output.parent / "Distance566Checks.lean").write_text(text)


def verify_family(rows, base, n, family):
    if not family:
        raise ValueError("Empty representative family")
    loads = [0] * n
    total = 0
    for entry in family:
        v = pack(entry["support"])
        w = entry["weight"]
        if type(w) is not int or w <= 0 or v.bit_length() > n:
            raise ValueError("Invalid representative or natural weight")
        if v != base ^ combination(rows, pack(entry["rows"])):
            raise ValueError("Incorrect same-class row combination")
        total += w
        for q in support(v):
            loads[q] += w
    cap = max(loads, default=0)
    # Every nonzero base in our application is a logical. Zero capacity cannot occur.
    return {"totalWeight": total, "cap": cap, "bound": (total + cap - 1) // cap if cap else 0}


def descend(v, coefficient, rows, costs, rng, sweeps=8):
    value = sum(costs[q] for q in support(v))
    order = list(range(len(rows)))
    for _ in range(sweeps):
        rng.shuffle(order)
        changed = False
        for i in order:
            row = rows[i]
            delta = sum((-costs[q] if (v >> q) & 1 else costs[q]) for q in support(row))
            if delta < -1e-10:
                v ^= row
                coefficient ^= 1 << i
                value += delta
                changed = True
        if not changed:
            break
    return v, coefficient, value


def search_family(rows, base, n, samples, rng, deadline):
    loads = [0] * n
    family = []
    best = []
    best_ratio = 0
    current, coefficient, _ = descend(base, 0, rows, [1.0] * n, rng, 40)
    min_weight = current.bit_count()
    for _ in range(samples):
        if time.monotonic() >= deadline:
            break
        # Multiplicative load penalties provide pricing candidates, not an LP optimum.
        average = max(1.0, sum(loads) / n)
        costs = [math.exp(min(12.0, 3.0 * v / average)) for v in loads]
        winner = None
        for attempt in range(4):
            v, c = current, coefficient
            if attempt:
                for _ in range(4 + 5 * attempt):
                    i = rng.randrange(len(rows))
                    v ^= rows[i]
                    c ^= 1 << i
            candidate = descend(v, c, rows, costs, rng, 15)
            if winner is None or candidate[2] < winner[2]:
                winner = candidate
        current, coefficient, _ = winner
        min_weight = min(min_weight, current.bit_count())
        family.append({"support": support(current), "rows": support(coefficient), "weight": 1})
        for q in support(current):
            loads[q] += 1
        ratio = len(family) / max(loads)
        if ratio > best_ratio:
            best_ratio = ratio
            best = list(family)
    summary = verify_family(rows, base, n, best) if best else None
    return {"family": best, "arithmetic": summary, "sampled": len(family), "min_weight": min_weight}


def structural_pilot(code):
    """Complete small-cycle census and sampled trellis-state dimensions.

    Boundary membership is numerical. Trellis measurements describe only the
    supplied orders, with no lower bound on the best possible ordering.
    """
    n = code["n"]
    result = {}
    for side, opposite in (("X", "Z"), ("Z", "X")):
        rows = [pack(r) for r in code["checks"][opposite]]
        stabilizers = echelon([pack(r) for r in code["checks"][side]])
        columns = [pack(i for i, r in enumerate(rows) if (r >> q) & 1) for q in range(n)]
        by_column = {}
        for q, c in enumerate(columns):
            by_column.setdefault(c, []).append(q)
        cycles = [[q] for q, c in enumerate(columns) if c == 0]
        for a in range(n):
            for b in range(a + 1, n):
                syndrome = columns[a] ^ columns[b]
                if not syndrome:
                    cycles.append([a, b])
                cycles.extend([a, b, c] for c in by_column.get(syndrome, []) if c > b)
        if any(reduce_vector(pack(v), stabilizers) for v in cycles):
            raise ValueError("Found a nontrivial logical of weight at most three")
        orders = {"literal": list(range(n)), "interleaved_blocks": []}
        for i in range(n // 2):
            orders["interleaved_blocks"].extend([i, i + n // 2])
        if n % 2:
            orders["interleaved_blocks"].append(n - 1)
        trellis = {}
        full_rank = len(echelon(rows))
        for name, order in orders.items():
            left = 0
            all_bits = (1 << n) - 1
            values = []
            for i, q in enumerate(order, 1):
                left |= 1 << q
                if i % 16 == 0 or i == n:
                    rank_left = len(echelon([r & left for r in rows]))
                    rank_right = len(echelon([r & (all_bits ^ left) for r in rows]))
                    values.append([i, rank_left + rank_right - full_rank])
            trellis[name] = {
                "sampled_cuts": values,
                "largest_sampled_state_dimension": max(v[1] for v in values),
            }
        result[side] = {
            "all_nonzero_cycles_weight_at_most_three": cycles,
            "all_listed_cycles_are_boundaries": True,
            "all_cycles_even": all(v.bit_count() % 2 == 0 for v in kernel(rows, n)),
            "trellis": trellis,
        }
    return result


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("mode", choices=["coordinates", "packing", "structure"])
    parser.add_argument("--upstream", type=Path, required=True)
    parser.add_argument("--out", type=Path, required=True)
    parser.add_argument("--lean-root", type=Path)
    parser.add_argument("--samples", type=int, default=96)
    parser.add_argument("--seconds", type=int, default=600)
    parser.add_argument("--seed", type=int, default=56620)
    args = parser.parse_args()
    start = time.monotonic()
    args.out.mkdir(parents=True, exist_ok=True)
    codes = {n: read_code(args.upstream / f"codes/{n}-18-20.json", n) for n in (566, 578)}
    records = {n: coordinates(code) for n, code in codes.items()}
    if args.mode == "coordinates":
        result = {"revision": REVISION, "input_sha256": HASHES, "coordinates": records}
        (args.out / "coordinates.json").write_text(json.dumps(result, indent=2) + "\n")
        if args.lean_root:
            emit_coordinates(records[566], args.lean_root / "Input/Distance566Data.lean")
    elif args.mode == "structure":
        result = {
            "revision": REVISION,
            "input_sha256": HASHES,
            "results": {n: structural_pilot(code) for n, code in codes.items()},
            "scope": "Numerical census only; no Lean bound or ordering-independent complexity claim",
        }
        (args.out / "structure.json").write_text(json.dumps(result, indent=2) + "\n")
    else:
        deadline = start + args.seconds
        rng = random.Random(args.seed)
        result = {"revision": REVISION, "seed": args.seed, "samples": args.samples, "families": []}
        # Round robin gives both sectors and both endpoints a fair bounded pilot.
        for i in range(18):
            for n in (566, 578):
                for side in ("X", "Z"):
                    if time.monotonic() >= deadline:
                        break
                    rows = [pack(v) for v in codes[n]["checks"][side]]
                    base = pack(records[n][side][i])
                    entry = search_family(rows, base, n, args.samples, rng, deadline)
                    entry.update({"n": n, "side": side, "coordinate": i})
                    result["families"].append(entry)
        result["elapsed_seconds"] = round(time.monotonic() - start, 3)
        result["scope"] = "Restricted-family heuristic; failed searches prove no impossibility"
        (args.out / "packing.json").write_text(json.dumps(result, indent=2) + "\n")
    manifest = {
        f.name: hashlib.sha256(f.read_bytes()).hexdigest()
        for f in args.out.glob("*.json")
        if f.name != "sha256.json"
    }
    (args.out / "sha256.json").write_text(json.dumps(manifest, indent=2) + "\n")
    print(json.dumps({"mode": args.mode, "elapsed_seconds": round(time.monotonic() - start, 3)}))


if __name__ == "__main__":
    main()
